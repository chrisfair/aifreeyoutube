// LexicalRule associates a specific keyword/phrase pattern with a weight and diagnostic explanation.
type LexicalRule struct {
	Phrase      string
	Weight      float64
	Description string
}

// RegexRule associates a pre-compiled regular expression with a weight and diagnostic explanation.
type RegexRule struct {
	Regex       *regexp.Regexp
	Weight      float64
	Confidence  float64
	Category    string
	Name        string
	Description string
}

